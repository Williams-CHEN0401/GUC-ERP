import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {ids} from './worklog-save-fixture.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.WORKLOG_TEST_URL||'http://127.0.0.1:4210';
const out=new URL('../tmp/title-picker/',import.meta.url);await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
 await context.route('**/*',route=>new URL(route.request().url()).origin===base?route.continue():route.abort());
 page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>dialog.dismiss());page.setDefaultTimeout(10000);
 const snapshot=async()=>await(await context.request.get(base+'/api/inventory?scope=worklogs')).json();
 const form=page.locator('#modalForm');
 const submit=async()=>{const pending=page.waitForResponse(r=>r.url().endsWith('/api/inventory')&&r.request().method()==='POST');await form.locator('button[type="submit"]').click();const response=await pending;assert.equal(response.status(),201,await response.text());await page.locator('#simpleModal').waitFor({state:'hidden'});return(await response.json()).result;};
 const initial=await snapshot(),original=initial.projects.find(p=>p.name==='應用數學系原工作內容'),target=initial.projects.find(p=>p.name==='應用數學系可選工作內容');
 const originalLog=initial.site_work_logs.find(log=>log.project_id===original.id);
 await page.goto(base+'/?page=worklogs');
 assert.ok(await page.locator('body').innerText());
 assert.equal(await page.locator('.vite-error-overlay,[data-nextjs-dialog]').count(),0);
 await page.locator('#worklogTable strong').filter({hasText:original.name}).dblclick();
 const choice=form.locator('#workLogProjectChoice');
 assert.ok((await choice.locator('option').allTextContents()).some(text=>text.includes(target.name)));
 assert.ok(!(await choice.locator('option').allTextContents()).some(text=>text.includes('已完成')));
 assert.equal(await form.locator('[name="projectName"]').getAttribute('readonly'),null);
 await choice.selectOption(target.id);assert.equal(await form.locator('[name="projectName"]').inputValue(),target.name);
 assert.equal(await form.locator('[name="workType"]').isDisabled(),true);
 await page.screenshot({path:fileURLToPath(new URL('selection-desktop.png',out)),fullPage:true});
 const moved=await submit();assert.equal(moved.work_log.id,originalLog.id);assert.equal(moved.work_log.project_id,target.id);
 await page.reload();let data=await snapshot();assert.equal(data.projects.find(p=>p.id===original.id).name,original.name);assert.equal(data.projects.find(p=>p.id===target.id).name,target.name);
 await page.locator('#worklogTable strong').filter({hasText:target.name}).first().dblclick();
 await form.locator('[name="projectName"]').fill('手動輸入同步名稱');
 assert.equal(await form.locator('[name="workType"]').isDisabled(),false);
 await submit();await page.reload();data=await snapshot();
 assert.equal(data.projects.find(p=>p.id===target.id).name,'手動輸入同步名稱');
 assert.ok(data.site_work_logs.filter(log=>log.project_id===target.id).every(log=>log.title==='手動輸入同步名稱'));
 await page.locator('[data-open="workLogModal"]').click();
 await form.locator('[name="customerCategory"]').selectOption('school');await form.locator('[name="customerId"]').selectOption(ids.customer);await form.locator('[name="departmentId"]').selectOption(ids.department);
 await form.locator('[name="projectName"]').fill('維修收件日期瀏覽器測試');await form.locator('[name="logDate"]').fill('2026-09-04');
 await form.locator('[name="workType"]').selectOption('維修紀錄');await form.locator('[name="workerIds"]').check();
 await form.locator('[name="eventType"]').selectOption('REPAIR');await form.locator('[name="eventServiceId"]').selectOption(ids.service);
 await form.locator('[name="eventOccurredAt"]').fill('2026-09-06');
 await form.locator('[name="eventInventoryCategoryId"]').selectOption(ids.category);await form.locator('[name="eventInventoryItemId"]').selectOption(ids.item);
 await form.locator('[name="eventCause"]').fill('瀏覽器測試故障');
 const created=await submit(),repairId=created.created_repair_item_ids[0];
 assert.ok(repairId);data=await snapshot();assert.equal(data.repair_items.find(r=>r.id===repairId).received_on,'2026-09-04','receipt uses log date, not event date or today');
 await page.reload();await page.locator('#worklogTable strong').filter({hasText:'維修收件日期瀏覽器測試'}).dblclick();
 await form.locator('[name="logDate"]').fill('2026-09-05');await submit();await page.reload();data=await snapshot();
 assert.equal(data.repair_items.find(r=>r.id===repairId).received_on,'2026-09-05');assert.equal(data.repair_items.length,1,'edit does not duplicate repairs');
 await page.locator('#worklogTable strong').filter({hasText:'維修收件日期瀏覽器測試'}).dblclick();
 assert.equal(await form.getByLabel('科室',{exact:true}).inputValue(),'應用數學系');
 await page.setViewportSize({width:390,height:844});await choice.selectOption(original.id);
 await page.screenshot({path:fileURLToPath(new URL('selection-mobile.png',out)),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 assert.deepEqual(errors,[]);
 await context.close();console.log('PASS browser: dropdown -> single-log move -> reload; manual shared rename -> reload; repair creation/date edit -> matching received date; preserved department, no duplicate repairs; desktop/mobile no page errors or overflow.');
}finally{await browser.close();}

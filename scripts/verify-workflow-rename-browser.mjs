import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {ids} from './worklog-save-fixture.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const out=new URL('../tmp/workflow-rename/',import.meta.url);await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
 await context.route('**/*',route=>new URL(route.request().url()).origin==='http://127.0.0.1:4200'?route.continue():route.abort());
 page.setDefaultTimeout(10000);page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.dismiss());
 const form=page.locator('#modalForm'),name='共用名稱瀏覽器測試-'+Date.now();
 const submit=async()=>{const response=page.waitForResponse(r=>r.url().endsWith('/api/inventory')&&r.request().method()==='POST');await form.locator('button[type="submit"]').click();const result=await response;assert.equal(result.status(),201,await result.text());await page.locator('#simpleModal').waitFor({state:'hidden'});return (await result.json()).result;};
 await page.goto('http://127.0.0.1:4200/?page=worklogs');
 await page.locator('[data-open="workLogModal"]').click();
 await form.locator('[name="customerCategory"]').selectOption('school');
 await form.locator('[name="customerId"]').selectOption(ids.customer);
 await form.locator('[name="departmentId"]').selectOption(ids.department);
 await form.locator('[name="projectName"]').fill(name);
 await form.locator('[name="workType"]').selectOption('文書作業');
 await form.locator('[name="timePeriod"]').fill('上午');
 await form.locator('[name="workerIds"]').check();
 await form.locator('[name="summary"]').fill('保留工作內容與其他欄位');
 await submit();
 await page.reload();await page.locator('#worklogTable strong').filter({hasText:name}).dblclick();
 assert.equal(await form.locator('[name="projectName"]').getAttribute('readonly'),null);
 await form.locator('[name="projectName"]').fill('已同步-'+name);
 await submit();await page.reload();
 await page.locator('#worklogTable strong').filter({hasText:'已同步-'+name}).dblclick();
 assert.equal(await form.locator('[name="projectName"]').inputValue(),'已同步-'+name);
 assert.equal(await form.locator('[name="summary"]').inputValue(),'保留工作內容與其他欄位');
 assert.equal(await form.locator('[name="timePeriod"]').inputValue(),'上午');
 assert.equal(await form.getByLabel('科室',{exact:true}).inputValue(),'應用數學系');
 await page.screenshot({path:fileURLToPath(new URL('rename-desktop.png',out)),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:fileURLToPath(new URL('rename-mobile.png',out)),fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
 assert.deepEqual(errors,[]);await context.close();
 console.log('PASS ERP UI -> actual Gateway -> PostgreSQL -> reload: shared project title updated, department/content/time retained, desktop/mobile.');
}finally{await browser.close();}

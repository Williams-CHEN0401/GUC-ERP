import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {assignmentManagementServer,planUsers} from './assignment-management-fixture.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const f=await assignmentManagementServer();await new Promise(r=>f.server.listen(0,'127.0.0.1',r));
const base='http://127.0.0.1:'+f.server.address().port,browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];page.setDefaultTimeout(10000);page.on('pageerror',e=>{errors.push(e.message);console.error('PAGE',e.message);});
 await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
 await page.goto(base+'/?page=appointments&test_user=admin');
 await page.locator('[data-system-choice="erp"]').click({timeout:3000}).catch(()=>{});
 await page.locator('[data-appointment-tab="assignments"]').click();
 await page.locator('#assignmentManagementPane [data-open="workAssignmentModal"]').click();
 await page.locator('#simpleModal.open').waitFor().catch(async e=>{console.error((await page.locator('body').innerText()).slice(-3000));throw e;});
 await page.selectOption('[name="assignmentProjectId"]',f.planProjects.small);
 await page.locator('[name="assigneeUserIds"][value="'+planUsers.A+'"]').check();
 await page.fill('[name="instructions"]','瀏覽器工作指派驗收');
 await page.locator('#modalForm [type="submit"]').click();
 await page.waitForFunction(()=>!document.querySelector('#simpleModal').classList.contains('open'));
 await page.locator('#assignmentManagementTable [data-assignment-edit]').first().click();
 await page.locator('#simpleModal.open').waitFor();
 await page.locator('[name="assigneeUserIds"][value="'+planUsers.A+'"]').uncheck();
 await page.locator('[name="assigneeUserIds"][value="'+planUsers.B+'"]').check();
 await page.selectOption('[name="assignmentStatus"]','in_progress');await page.fill('[name="instructions"]','瀏覽器修改完成');
 await page.locator('#modalForm [type="submit"]').click();
 await page.waitForFunction(()=>!document.querySelector('#simpleModal').classList.contains('open'));
 assert.ok((await page.locator('#assignmentManagementTable').innerText()).includes('瀏覽器修改完成'));
 const output=new URL('../tmp/assignment-management/',import.meta.url);await mkdir(output,{recursive:true});
 await page.screenshot({path:fileURLToPath(new URL('desktop.png',output)),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.evaluate(()=>Promise.all(document.getAnimations().map(animation=>animation.finished.catch(()=>{}))));await page.screenshot({path:fileURLToPath(new URL('mobile.png',output)),fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await page.setViewportSize({width:1440,height:1000});
 page.once('dialog',d=>d.accept());await page.locator('[data-assignment-cancel]').first().click();
 await page.waitForFunction(()=>!document.querySelector('[data-assignment-cancel]'));
 await page.locator('#assignmentManagementPane button[aria-expanded]').click();
 await page.selectOption('#assignmentManagementStatus','cancelled');assert.ok((await page.locator('#assignmentManagementTable').innerText()).includes('已取消'));
 await page.keyboard.press('Escape');
 await page.locator('[data-appointment-tab="list"]').click();assert.ok(await page.locator('#appointmentTable').isVisible());
 await page.locator('[data-page="dashboard"].nav-item').click();assert.equal(await page.locator('#dashboard [data-open="workAssignmentModal"]').count(),0);
 assert.deepEqual(errors,[]);console.log('PASS actual browser: appointment tabs, create assignment, edit/reassign/status, cancel, original appointment list, Dashboard management entry removed; no page errors');
}finally{await browser.close();await new Promise(r=>f.server.close(r));await f.db.close();}
